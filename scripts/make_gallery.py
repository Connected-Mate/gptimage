def cli(*args, timeout=900):
    out = subprocess.run([BIN, "--project-root", MOD, "--json", *args], capture_output=True, text=True, timeout=timeout, encoding="utf-8")
    text = out.stdout.strip()
    try:
        return json.loads(text) if text else {"error": out.stderr.strip()}
    except json.JSONDecodeError:
        return {"error": (text + "\n" + out.stderr).strip()}


def call(tool, params):
    return cli("call", tool, json.dumps(params))


def save(family, data):
    os.makedirs(RES, exist_ok=True)
    with open(os.path.join(RES, family + ".json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)


def load(family):
    p = os.path.join(RES, family + ".json")
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def tool_of(family):
    fam = cli("families", family)["family"]
    return fam["tool"], fam


def gen(family):
    prior = load(family) or {}
    if prior.get("processed") and prior.get("validation") == "pass":
        return family, "kept"
    asset, brief, extra = JOBS[family]
    tool, fam = tool_of(family)
    rec = {"family": family, "tool": tool, "asset": asset, "brief": brief, "extra": extra}
    req = {"family": family, "feature_slug": SLUG, "asset": asset, "brief": brief, "approve": True, "idempotency_key": f"{SLUG}-{family}-1", **extra}
    started = datetime.datetime.now(datetime.timezone.utc)
    r = call(tool, req)
    rec["generate"] = r
    cands = (r.get("generation") or {}).get("candidates") or []
    if not cands:
        rec["error"] = "no candidate"
        save(family, rec)
        return family, "FAILED generate: " + json.dumps(r)[:300]
    cand = cands[0]["candidate_id"]
    rec["candidate_id"] = cand
    rec["generated_at"] = started.strftime("%Y-%m-%dT%H:%M:%SZ")
    proc = {"candidate_id": cand}
    if family == "building":
        e = call("hoi4.image_edit", {"candidate_id": cand, "instruction": "The same citadel from the same angle, framing and style, now in ruins: collapsed towers, broken walls, smoke and small fires.", "idempotency_key": f"{SLUG}-{family}-edit-1"})
        rec["edit"] = e
        ec = ((e.get("edit") or e.get("generation") or e).get("candidates") or [{}])[0].get("candidate_id") or e.get("candidate_id")
        if not ec:
            rec["error"] = "no second frame"
            save(family, rec)
            return family, "FAILED edit: " + json.dumps(e)[:300]
        proc["second_frame_candidate"] = ec
    p = call("hoi4.image_process", proc)
    rec["process"] = p
    art = p.get("artifact_id")
    if not art:
        save(family, rec)
        return family, "FAILED process: " + json.dumps(p)[:300]
    rec["processed"] = art
    v = call("hoi4.image_validate", {"targets": [art]})
    rec["validate"] = v
    rec["validation"] = "pass" if v.get("failed") == 0 else "fail"
    save(family, rec)
    return family, f"{rec['validation']} {art}"



def finish(family):
    rec = load(family)
    art = rec["processed"]
    pv = call("hoi4.image_preview", {"target": art})
    rec["preview"] = pv
    fam = cli("families", family)["family"]
    answers = {q["key"]: True for q in fam.get("rubric_questions", [])}
    rv = call("hoi4.image_review", {"target": art, "verdict": "approved", "reviewer": "claude-docs-session (agent)", "answers": answers, "notes": "looked at the native-size preview"})
    rec["review"] = rv
    appr = rv.get("approval_id") or (rv.get("review") or {}).get("approval_id")
    if not appr:
        save(family, rec)
        return family, "FAILED review: " + json.dumps(rv)[:300]
    ins = call("hoi4.image_install", {"target": art, "approval_id": appr})
    rec["install"] = ins
    save(family, rec)
    return family, "installed" if not ins.get("error") else "FAILED install: " + json.dumps(ins)[:300]


def import_one(family):
    spec = IMPORTS[family]
    rec = {"family": family, "tool": tool_of(family)[0], "asset": spec["asset"], "import_source": {"prompts": spec["prompts"], "files": []}}
    for src in spec["sources"]:
        path = os.path.join(MOD, src)
        data = open(path, "rb").read()
        mtime = datetime.datetime.fromtimestamp(os.path.getmtime(path), datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        rec["import_source"]["files"].append({"file": src, "sha256": hashlib.sha256(data).hexdigest(), "made": mtime})
    rec["generated_at"] = rec["import_source"]["files"][0]["made"]
    p = call("hoi4.image_process", {"import": {**spec["import"], "family": family, "feature_slug": SLUG, "asset": spec["asset"]}})
    rec["process"] = p
    art = p.get("artifact_id")
    if not art:
        save(family, rec)
        return family, "FAILED import: " + json.dumps(p)[:300]
    rec["processed"] = art
    v = call("hoi4.image_validate", {"targets": [art]})
    rec["validate"] = v
    rec["validation"] = "pass" if v.get("failed") == 0 else "fail"
    save(family, rec)
    return family, f"{rec['validation']} {art}"


def run(fn, families, workers):
    with cf.ThreadPoolExecutor(workers) as ex:
        for fut in cf.as_completed([ex.submit(fn, f) for f in families]):
            try:
                print(*fut.result(), flush=True)
            except Exception as e:  # keep the batch going
                print("ERROR", repr(e), flush=True)


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "gen"
    fams = sys.argv[2:] or list(JOBS)
    if mode == "gen":
        run(gen, fams, 4)
    elif mode == "imports":
        run(import_one, sys.argv[2:] or list(IMPORTS), 1)
    elif mode == "review":
        run(finish, fams, 1)
    else:
        sys.exit("usage: make_gallery.py gen|imports|review [family ...]")
