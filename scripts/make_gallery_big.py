PAUSE_LOCK = threading.Lock()
ABORT = threading.Event()
STATE = {"backoff": 0, "single_until": float(os.environ.get("GALLERY_SINGLE_UNTIL", "0"))}


class Blocked(Exception):
    pass


def cli(*args, timeout=1200):
    out = subprocess.run([BIN, "--project-root", MOD, "--json", *args], capture_output=True, text=True, timeout=timeout, encoding="utf-8")
    text = out.stdout.strip()
    try:
        return json.loads(text) if text else {"error": {"message": out.stderr.strip()}}
    except json.JSONDecodeError:
        return {"error": {"message": (text + "\n" + out.stderr).strip()}}


def tool_version():
    out = subprocess.run([BIN, "--version"], capture_output=True, text=True).stdout.strip()
    return out.split()[-1] if out else "unknown"


def check_build():
    """GALLERY_EXPECT_VERSION (for example 0.3.0) must match the binary, or nothing is spent."""
    want = os.environ.get("GALLERY_EXPECT_VERSION")
    have = tool_version()
    if want and have != want:
        sys.exit(f"wrong build: expected hoi4-imagegen {want}, {BIN} is {have}")
    print(f"[{now()}] build hoi4-imagegen {have}, mod {MOD}", flush=True)


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


PROVIDER_TOOLS = ("hoi4.image_icon", "hoi4.image_picture", "hoi4.image_portrait", "hoi4.image_flag", "hoi4.image_unit", "hoi4.image_interface", "hoi4.image_generate", "hoi4.image_edit")
MIN_GAP = float(os.environ.get("GALLERY_MIN_GAP_SECONDS", "10"))  # seconds between two provider requests, all workers together
GAP_LOCK = threading.Lock()
LAST = {"t": 0.0}


def throttle():
    with GAP_LOCK:
        wait = LAST["t"] + MIN_GAP - time.time()
        if wait > 0:
            time.sleep(wait)
        LAST["t"] = time.time()


ONE = threading.Lock()
MODEL_ACCESS = [float(x) for x in os.environ.get("GALLERY_MODEL_ACCESS_TIMES", "").split(",") if x]  # answer times, earlier processes included
MODEL_ACCESS_LOCK = threading.Lock()


def model_access_backoff(msg):
    """The backend's "Unable to verify model access right now" (coordinator, 2026-11-05, until the tool's fallback
    covers it): one answer pauses this worker 5 minutes, a second within 15 minutes drops the run to one worker for 30
    minutes, and a third within 15 minutes stops the run, because it may come before a sign-out."""
    with MODEL_ACCESS_LOCK:
        t = time.time()
        MODEL_ACCESS.append(t)
        recent = [x for x in MODEL_ACCESS if t - x <= 15 * 60]
        n = len(recent)
        print(f"[{now()}] MODEL_ACCESS error {n} in 15 minutes: {msg[:160]}", flush=True)
        if n >= 3:
            ABORT.set()
            open(os.path.join(WORK, "STOP"), "w").close()
            print(f"[{now()}] BLOCKED model access errors keep coming: the run stops (no retry) until someone looks", flush=True)
            return
        if n == 2:
            STATE["single_until"] = t + 30 * 60
            print(f"[{now()}] MODEL_ACCESS backoff: one worker until {time.strftime('%H:%M:%SZ', time.gmtime(t + 1800))}", flush=True)
            return
    time.sleep(5 * 60)


def call(tool, params):
    """One operation, with pacing: a gap between provider requests, wait out a pause, back off on 429, stop on a rejected token."""
    reconciled = False
    last = None
    for attempt in range(8):
        while PAUSE.is_set() and not ABORT.is_set():
            time.sleep(5)
        if ABORT.is_set():
            raise Blocked("run aborted")
        provider = tool in PROVIDER_TOOLS and params.get("approve", True)
        if provider:
            throttle()
        if provider and time.time() < STATE.get("single_until", 0):
            with ONE:  # one worker at a time while the model-access backoff lasts
                r = cli("call", tool, json.dumps(params))
        else:
            r = cli("call", tool, json.dumps(params))
        err = r.get("error") if isinstance(r, dict) else None
        if not err:
            STATE["backoff"] = 0
            return r
        code = str(err.get("code", ""))
        msg = str(err.get("message", ""))
        if "unable to verify model access" in msg.lower():
            model_access_backoff(msg)
            return r  # the example fails and is retried at the end of the run
        if code == "provider_auth" or "401" in msg and "token" in msg.lower():
            ABORT.set()
            raise Blocked("the ChatGPT token was rejected: " + msg)
        if "429" in msg or "rate limit" in msg.lower() or err.get("retry_class") == "retry_later":
            with PAUSE_LOCK:
                if not PAUSE.is_set():
                    PAUSE.set()
                    wait = min(30, 5 * 2 ** STATE["backoff"])
                    STATE["backoff"] += 1
                    print(f"[{now()}] rate limited, pausing every worker for {wait} minutes", flush=True)
                    threading.Timer(wait * 60, PAUSE.clear).start()
            continue
        if err.get("retry_class") == "reconcile_first":
            key = params.get("idempotency_key")
            if key and not reconciled:
                reconciled = True
                cancel = cli("call", "hoi4.image_cancel", json.dumps({"idempotency_key": key, "reconcile": True}))
                print(f"[{now()}] reconciled {key}: {json.dumps(cancel)[:200]}", flush=True)
                continue
        last = r
        if "429" not in msg and "rate limit" not in msg.lower():
            return r
    return last if last else {"error": {"message": "gave up after repeated rate limits"}}


def rpath(family, asset):
    return os.path.join(RES, family, asset + ".json")


def load(family, asset):
    p = rpath(family, asset)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def save(family, asset, rec):
    os.makedirs(os.path.join(RES, family), exist_ok=True)
    with open(rpath(family, asset), "w", encoding="utf-8", newline="\n") as f:
        json.dump(rec, f, indent=1, ensure_ascii=False)


def briefs():
    return json.load(open(BRIEFS, encoding="utf-8"))


TOOLS = {}


def tool_of(family):
    # cached, and asked twice: under two workers a `families` call once answered without "family" and killed the run
    if family not in TOOLS:
        for _ in range(2):
            r = cli("families", family)
            if "family" in r:
                TOOLS[family] = r["family"]["tool"]
                break
            time.sleep(5)
        else:
            raise RuntimeError(f"families {family}: {json.dumps(r)[:300]}")
    return TOOLS[family]


def first_candidate(r):
    return ((r.get("generation") or {}).get("candidates") or [None])[0]


def standin(family, asset, brief, canvas, suffix, key, kind="gen", parent=None, instruction=None):
    """Make one counter or emblem frame with the tool's provider through gui_texture at the exact canvas."""
    feature = family
    if kind == "gen":
        r = call("hoi4.image_interface", {"family": "gui_texture", "feature_slug": feature, "asset": f"{asset}_{suffix}", "brief": brief, "canvas": canvas, "approve": True, "idempotency_key": key})
        cand = first_candidate(r)
    else:
        r = call("hoi4.image_edit", {"candidate_id": parent, "instruction": instruction, "idempotency_key": key})
        cand = (r.get("candidates") or [None])[0] or first_candidate(r) or ((r.get("edit") or {}).get("candidates") or [None])[0]
        if not cand and r.get("candidate_id"):
            cand = {"candidate_id": r["candidate_id"]}
    if not cand:
        return r, None, None
    p = call("hoi4.image_process", {"candidate_id": cand["candidate_id"]})
    return r, cand, p


def make_counter(job, attempt):
    family, asset, brief = job["family"], job["asset"], job["brief"]
    canvas = COUNTERS[family]
    rec = {"family": family, "asset": asset, "brief": brief, "style": None, "kind": "import", "attempt": attempt, "started_at": now(), "stand_in": "gui_texture"}
    key = f"big-{family}-{asset}-{attempt}"
    if family == "division_emblem":
        r1, c1, p1 = standin(family, asset, f"A Hearts of Iron IV division designer emblem symbol: {brief}. Two or three flat colours, clean thick shapes, wide composition, no text.", canvas, "e", key + "-e")
        rec["generate"] = r1
        if not c1 or not p1 or not p1.get("artifact_id"):
            rec["error"] = "stand-in generation failed"
            save(family, asset, rec)
            return "FAILED " + json.dumps(r1)[:200]
        rec["frame_artifacts"] = [p1["artifact_id"]]
        rec["stand_in_candidates"] = [c1["candidate_id"]]
        imp = {"path": p1["path"]}
    else:
        white = f"A Hearts of Iron IV military map counter pictogram: {brief}. A bold pure white silhouette, flat, no shading, thick simple shapes filling the frame, wide composition"
        r1, c1, p1 = standin(family, asset, white, canvas, "f1", key + "-f1")
        rec["generate"] = r1
        if not c1 or not p1 or not p1.get("artifact_id"):
            rec["error"] = "frame 1 failed"
            save(family, asset, rec)
            return "FAILED " + json.dumps(r1)[:200]
        r2, c2, p2 = standin(family, asset, None, canvas, "f2", key + "-f2", kind="edit", parent=c1["candidate_id"],
                             instruction="The same pictogram, same shape and position, but selected state: bright warm yellow with a soft glow, flat, transparent background.")
        rec["edit"] = r2
        if not c2 or not p2 or not p2.get("artifact_id"):
            rec["error"] = "frame 2 failed"
            save(family, asset, rec)
            return "FAILED " + json.dumps(r2)[:200]
        rec["frame_artifacts"] = [p1["artifact_id"], p2["artifact_id"]]
        rec["stand_in_candidates"] = [c1["candidate_id"], c2["candidate_id"]]
        imp = {"frames": [p1["path"], p2["path"]]}
    p = call("hoi4.image_process", {"import": {**imp, "family": family, "feature_slug": family, "asset": asset}})
    rec["process"] = p
    art = p.get("artifact_id")
    if not art:
        rec["error"] = "import failed"
        save(family, asset, rec)
        return "FAILED " + json.dumps(p)[:200]
    rec["processed"] = art
    v = call("hoi4.image_validate", {"targets": [art]})
    rec["validate"] = v
    rec["validation"] = "pass" if v.get("failed") == 0 else "fail"
    rec["finished_at"] = now()
    save(family, asset, rec)
    return f"{rec['validation']} {art}"


def style_on(name, family):
    """A pinned style is the DEFAULT of every family it lists (empty = all), and `style` is refused for a family it does not
    list. So a style lives in styles_off/ and is switched on for one family only while its request runs."""
    d = json.load(open(os.path.join(MOD, "styles_off", name + ".json"), encoding="utf-8"))
    d["families"] = [family]
    os.makedirs(os.path.join(MOD, ".hoi4-imagegen", "styles"), exist_ok=True)
    with open(os.path.join(MOD, ".hoi4-imagegen", "styles", name + ".json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(d, f, indent=2)


def style_off(name):
    p = os.path.join(MOD, ".hoi4-imagegen", "styles", name + ".json")
    if os.path.exists(p):
        os.remove(p)


def make_standard(job, attempt):
    family, asset, brief, style = job["family"], job["asset"], job["brief"], job.get("style")
    tool = tool_of(family)
    rec = {"family": family, "tool": tool, "asset": asset, "brief": brief, "style": style, "kind": "generate", "attempt": attempt, "started_at": now(), "tool_version": tool_version()}
    req = {"family": family, "feature_slug": family, "asset": asset, "brief": brief, "approve": True, "idempotency_key": f"big-{family}-{asset}-{attempt}"}
    if family in MOD_CANVAS:
        req["canvas"] = MOD_CANVAS[family]
    if job.get("references"):
        # caller references (per-brief vanilla anchors or the TNO section's); from 0.3.2 their form wins over vanilla's
        req["references"] = [{"path": r["path"], "role": r["role"]} for r in job["references"]]
        rec["anchors"] = job["references"]
    if style:
        req["style"] = style
        style_on(style, family)
    try:
        r = call(tool, req)
    finally:
        if style:
            style_off(style)
    rec["generate"] = r
    cand = first_candidate(r)
    if not cand:
        rec["error"] = (r.get("error") or {}).get("message", "no candidate")
        save(family, asset, rec)
        return "FAILED " + json.dumps(r)[:240]
    rec["candidate_id"] = cand["candidate_id"]
    proc = {"candidate_id": cand["candidate_id"]}
    if family == "building":
        e = call("hoi4.image_edit", {"candidate_id": cand["candidate_id"], "instruction": "The same building from the same angle, framing and style, now in ruins: collapsed walls, broken roof, smoke and small fires.", "idempotency_key": f"big-{family}-{asset}-{attempt}-edit"})
        rec["edit"] = e
        ec = (e.get("candidates") or [None])[0] or first_candidate(e) or ((e.get("edit") or {}).get("candidates") or [None])[0]
        ecid = (ec or {}).get("candidate_id") or e.get("candidate_id")
        if not ecid:
            rec["error"] = "no second frame"
            save(family, asset, rec)
            return "FAILED edit " + json.dumps(e)[:200]
        proc["second_frame_candidate"] = ecid
    p = call("hoi4.image_process", proc)
    rec["process"] = p
    art = p.get("artifact_id")
    if not art:
        rec["error"] = (p.get("error") or {}).get("message", "process failed")
        save(family, asset, rec)
        return "FAILED process " + json.dumps(p)[:200]
    rec["processed"] = art
    v = call("hoi4.image_validate", {"targets": [art]})
    rec["validate"] = v
    rec["validation"] = "pass" if v.get("failed") == 0 else "fail"
    rec["finished_at"] = now()
    save(family, asset, rec)
    return f"{rec['validation']} {art}"


PRIORITY = os.path.join(WORK, "priority")
PRIORITY_LOCK = threading.Lock()


def run_priority():
    """Other sessions' generation jobs, run between two of ours so the login still sees one request at a time.

    A file .work/priority/<name>.json holds {"cwd": ..., "argv": [...]}. It runs once, its output goes to <name>.log and the
    file is renamed to <name>.done."""
    if not os.path.isdir(PRIORITY) or os.environ.get("GALLERY_IN_PRIORITY"):
        return  # a priority job never starts the priority queue again from inside itself
    with PRIORITY_LOCK:
        for name in sorted(os.listdir(PRIORITY)):
            if not name.endswith(".json"):
                continue
            path = os.path.join(PRIORITY, name)
            spec = json.load(open(path, encoding="utf-8"))
            print(f"[{now()}] priority job {name}: {' '.join(spec['argv'])}", flush=True)
            with open(path[:-5] + ".log", "w", encoding="utf-8") as log:
                env = {**os.environ, **spec.get("env", {})}
                rc = subprocess.run(spec["argv"], cwd=spec["cwd"], env=env, stdout=log, stderr=subprocess.STDOUT).returncode
            os.replace(path, path[:-5] + ".done")
            print(f"[{now()}] priority job {name} exited {rc}", flush=True)


def make(job):
    run_priority()
    family, asset = job["family"], job["asset"]
    if os.path.exists(os.path.join(WORK, "STOP")):
        return f"{family}/{asset}", "BLOCKED stop file present"
    prior = load(family, asset)
    if prior and prior.get("processed") and prior.get("validation") == "pass":
        return f"{family}/{asset}", "kept"
    attempt = (prior or {}).get("attempt", 1)  # same key: a half-finished request replays for free
    history = []
    if prior and prior.get("redo"):
        old = {k: v for k, v in prior.items() if k not in ("redo", "history", "preview")}
        history = prior.get("history", []) + [old]
        attempt = prior.get("attempt", 1) + 1
    try:
        # hoi4-imagegen 0.3.0 generates counters and division emblems itself; the gui_texture stand-in is only for 0.2.x
        out = make_counter(job, attempt) if family in COUNTERS and os.environ.get("GALLERY_COUNTER_STANDIN") else make_standard(job, attempt)
    except Blocked as e:
        return f"{family}/{asset}", "BLOCKED " + str(e)
    except Exception as e:  # noqa: BLE001 - one broken example is logged as failed and the run goes on
        return f"{family}/{asset}", f"FAILED {type(e).__name__}: {str(e)[:200]}"
    if history:
        rec = load(family, asset)
        rec["history"] = history
        save(family, asset, rec)
    return f"{family}/{asset}", out


def held():
    """Regexes on "family/asset" from .work/held.txt (one per line, # comments): examples waiting for a later build.
    Read when a run builds its job list, so a queue already written can still leave a family out."""
    p = os.path.join(WORK, "held.txt")
    if not os.path.exists(p):
        return []
    return [ln.strip() for ln in open(p, encoding="utf-8") if ln.strip() and not ln.startswith("#")]


def jobs(families):
    """Jobs in order. An argument is `family` or `family:N` (only the first N examples of the family)."""
    b = briefs()
    out = []
    names = families or ORDER + [f for f in b if f not in ORDER]
    for spec in names:
        fam, _, n = spec.partition(":")
        for item in b.get(fam, [])[: int(n) if n else None]:
            item = dict(item)
            skip = os.environ.get("GALLERY_SKIP")  # regex on "family/asset", e.g. ^commander_trait/.*tank
            if skip and re.search(skip, f"{fam}/{item['asset']}"):
                continue
            if any(re.search(rx, f"{fam}/{item['asset']}") for rx in held()):
                continue
            if fam in PORTRAITS and not os.environ.get("GALLERY_NO_PORTRAIT_LINE"):
                # W5's 0.3.2 portrait line, added to the brief until the build carries it
                item["brief"] = item["brief"].rstrip() + " " + PORTRAIT_LINE
            if os.environ.get("GALLERY_NO_STYLES"):
                # the vanilla-style gallery: mod styles are shown in their own (TNO) section instead
                item["style"] = None
            if os.environ.get("GALLERY_PICK_ANCHORS") and fam not in NO_ANCHORS and not item.get("references"):
                # per-brief vanilla anchors instead of the family's one automatic set
                import gallery_anchors
                info = FAMILY_INFO.get(fam) or FAMILY_INFO.setdefault(fam, cli("families", fam)["family"])
                try:
                    item["references"] = gallery_anchors.pick(fam, info, item["asset"], item["brief"], MOD, WORK) or None
                except Exception as e:  # noqa: BLE001 - a family the picker cannot index runs without anchors, logged
                    print(f"[{now()}] anchors for {fam}/{item['asset']} failed ({type(e).__name__}: {e}); no anchors", flush=True)
                    item["references"] = None
            if fam in COUNTERS and not os.environ.get("GALLERY_COUNTER_STANDIN"):
                # the model draws one black silhouette and the tool renders vanilla's material and NATO box
                item["brief"] = re.sub(r"\bwhite\b", "black", item["brief"], flags=re.I)
            out.append({"family": fam, **item})
    return out


def cmd_gen(args):
    workers = 1  # one request at a time unless told otherwise
    if "--workers" in args:
        i = args.index("--workers")
        workers = int(args[i + 1])
        del args[i : i + 2]
    limit = None
    if "--limit" in args:
        i = args.index("--limit")
        limit = int(args[i + 1])
        del args[i : i + 2]
    check_build()
    todo = jobs(args)
    if limit:
        todo = todo[:limit]
    print(f"[{now()}] {len(todo)} examples, {workers} workers", flush=True)
    done = 0
    with cf.ThreadPoolExecutor(workers) as ex:
        futs = [ex.submit(make, j) for j in todo]
        for fut in cf.as_completed(futs):
            name, out = fut.result()
            done += 1
            if out != "kept":
                print(f"[{now()}] ({done}/{len(todo)}) {name} {out}", flush=True)
            if out.startswith("BLOCKED"):
                ABORT.set()
    if ABORT.is_set():
        print("STOPPED: sign in again and rerun `gen`; finished examples are skipped.", flush=True)
        sys.exit(3)


def cmd_status(args):
    b = briefs()
    tot = {"pass": 0, "fail": 0, "todo": 0, "installed": 0}
    for fam in ORDER + [f for f in b if f not in ORDER]:
        c = {"pass": 0, "fail": 0, "todo": 0, "installed": 0}
        for item in b.get(fam, []):
            r = load(fam, item["asset"])
            if not r or not r.get("processed"):
                c["todo"] += 1
            elif r.get("validation") == "pass":
                c["pass"] += 1
                if r.get("install") and not r["install"].get("error"):
                    c["installed"] += 1
            else:
                c["fail"] += 1
        print(f"{fam:26} pass {c['pass']:3} fail {c['fail']:2} todo {c['todo']:3} installed {c['installed']:3}")
        for k in c:
            tot[k] += c[k]
    print("TOTAL", tot)


def cmd_redo(args):
    """redo family/asset ... | redo --failed family: forget the current attempt (kept in `history`) so `gen` makes a new one."""
    if args and args[0] == "--failed":
        names = [f"{args[1]}/{i['asset']}" for i in briefs()[args[1]] if (load(args[1], i["asset"]) or {}).get("verdict", {}).get("verdict") == "fail"]
    else:
        names = args
    for a in names:
        fam, asset = a.split("/")
        r = load(fam, asset)
        if r:
            r["redo"] = True
            r.pop("processed", None)
            save(fam, asset, r)
            print("redo", a)


def cmd_verdict(args):
    """verdict family [--fail asset:reason ...]: record the person's first look at every example of the family.

    Every validated example of the current attempt without a verdict gets `pass`, except the listed ones, which get `fail`
    with the reason and a `changes_requested` review in the tool's ledger. Nothing is installed here."""
    family = args[0]
    fails = {}
    rest = args[1:]
    i = 0
    while i < len(rest):
        if rest[i] == "--fail":
            asset, _, reason = rest[i + 1].partition(":")
            fails[asset] = reason.strip()
            i += 2
        else:
            i += 1
    fam = cli("families", family)["family"]
    for item in briefs()[family]:
        r = load(family, item["asset"])
        if not r or not r.get("processed") or r.get("validation") != "pass" or r.get("verdict"):
            continue
        if item["asset"] in fails:
            r["verdict"] = {"verdict": "fail", "reason": fails[item["asset"]], "by": "claude-docs-session (agent)", "at": now(), "attempt": r.get("attempt", 1)}
            answers = {q["key"]: False for q in fam.get("rubric_questions", [])}
            r["rejection"] = call("hoi4.image_review", {"target": r["processed"], "verdict": "changes_requested", "reviewer": "claude-docs-session (agent)", "answers": answers, "notes": fails[item["asset"]]})
        else:
            r["verdict"] = {"verdict": "pass", "reason": "looked at it at native size and enlarged next to the family's references: readable, on subject, clean edges and alpha", "by": "claude-docs-session (agent)", "at": now(), "attempt": r.get("attempt", 1)}
        save(family, item["asset"], r)
    print(family, "verdicts recorded;", len(fails), "failed")


def finish(job):
    family, asset = job["family"], job["asset"]
    rec = load(family, asset)
    if not rec or rec.get("validation") != "pass" or (rec.get("verdict") or {}).get("verdict") != "pass":
        return f"{family}/{asset}", "skipped (not validated or no pass verdict)"
    if rec.get("install") and not rec["install"].get("error"):
        return f"{family}/{asset}", "kept"
    art = rec["processed"]
    rec["preview"] = call("hoi4.image_preview", {"target": art})
    fam = cli("families", family)["family"]
    answers = {q["key"]: True for q in fam.get("rubric_questions", [])}
    rv = call("hoi4.image_review", {"target": art, "verdict": "approved", "reviewer": "claude-docs-session (agent)", "answers": answers, "notes": "looked at the contact sheet of this family's examples at native size"})
    rec["review"] = rv
    appr = rv.get("approval_id")
    if not appr:
        save(family, asset, rec)
        return f"{family}/{asset}", "FAILED review " + json.dumps(rv)[:200]
    rec["install"] = call("hoi4.image_install", {"target": art, "approval_id": appr})
    save(family, asset, rec)
    return f"{family}/{asset}", "installed" if not rec["install"].get("error") else "FAILED install " + json.dumps(rec["install"])[:200]


def cmd_review(args):
    skip = set()
    if "--except" in args:
        i = args.index("--except")
        skip = set(args[i + 1].split(","))
        del args[i : i + 2]
    if "--approve-all" in args:
        args.remove("--approve-all")
    for j in jobs(args):
        if f"{j['family']}/{j['asset']}" in skip:
            continue
        name, out = finish(j)
        if out != "kept":
            print(name, out, flush=True)


