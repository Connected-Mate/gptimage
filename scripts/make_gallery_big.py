#!/usr/bin/env python3
"""Make the big gallery (docs/gallery/<family>/) with the real tool, paced and resumable.

  make_gallery_big.py styles            pin the three mod style references (linocut, gouache, ink)
  make_gallery_big.py gen [family ...]  generate + process + validate every missing example (paced, resumable)
  make_gallery_big.py status            counts per family
  make_gallery_big.py review [family ...] [--approve-all] [--except id,id]
                                        preview, review (approved) and install, one at a time. Only after a person has
                                        looked at every image. Examples listed in --except are not approved.
  make_gallery_big.py verdict family [--fail asset:reason ...]
                                        record the first look at every example of a family (pass, or fail with a reason)
  make_gallery_big.py redo family/asset ... | redo --failed family
                                        keep the attempt in `history` and make a new one on the next `gen` (a fix first)

Inputs: scripts/gallery_briefs.json ({family: [{asset, brief, style}]}). State: .work/gallery-mod (the scratch mod) and
.work/big-results/<family>/<asset>.json. Everything is generated by hoi4-imagegen on the ChatGPT-login provider. The three
import-only families (counters and division emblem) are not generated by the tool: their frames are made by the tool's
own provider through the `gui_texture` family at the exact counter canvas, then imported with hoi4.image_process.

Pacing: one request at a time by default (--workers N for more), at least GALLERY_MIN_GAP_SECONDS (10) between provider requests. A 429 pauses every worker with exponential backoff (5, 10, 20, 30 minutes). A
rejected token stops the run and exits with code 3 (sign in again, then rerun: finished examples are skipped, and the
idempotency key makes a repeated request replay instead of paying again).
"""
