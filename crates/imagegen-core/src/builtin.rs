/// The built-in profile list, one per category.
pub fn profiles() -> Vec<Profile> {
    rows()
        .into_iter()
        .map(|r| {
            let canvas = r.canvas;
            Profile {
                id: r.category.as_str().to_string(),
                category: r.category,
                canvas,
                accepted: r.accepted.to_vec(),
                margin: r.margin,
                frames: r.frames,
                source: r.source.to_string(),
                origin: ProfileOrigin::Builtin,
                overridden: Vec::new(),
                vanilla: Some(VanillaDefault { canvas, source: r.source.to_string() }),
                imagegen: ImagegenSpec {
                    automation: r.automation,
                    background: r.background,
                    container: r.container,
                    folder: r.folder.to_string(),
                    prefix: r.prefix.to_string(),
                    sprite: r.sprite.map(|(gfx_file, name, companions)| SpriteSpec {
                        gfx_file: gfx_file.to_string(),
                        name: name.to_string(),
                        companions: companions.iter().map(|s| s.to_string()).collect(),
                    }),
                    variants: if r.category == Category::FlagSet { flag_variants() } else { Vec::new() },
                    checks: r.checks.iter().map(|s| s.to_string()).collect(),
                    reference_dirs: vec![format!("references/{}", r.category.as_str())],
                    rubric: r.rubric.to_string(),
                    prompt: PromptSpec {
                        rules: r.rules.iter().map(|s| s.to_string()).collect(),
                        negative: r.negative.iter().map(|s| s.to_string()).collect(),
                    },
                    grayscale: r.grayscale,
                },
            }
        })
        .collect()
}

/// A profile for a kit row this crate has no category for.
pub fn custom_profile(id: &str, canvas: [u32; 2]) -> Profile {
    let mut p = profiles().into_iter().find(|p| p.category == Category::Custom).expect("custom profile exists");
    p.id = id.to_string();
    p.canvas = canvas;
    p.accepted = vec![canvas];
    p.vanilla = None;
    p.origin = ProfileOrigin::Kit;
    p
}
